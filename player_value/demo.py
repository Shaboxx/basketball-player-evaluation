"""Run the complete deterministic offline example: python -m player_value.demo."""
import argparse
import csv
import json
from pathlib import Path
import platform
import torch
from .baselines import ContextNull, OneHotPoints
from .data import SPLITS, Transform, canonical_jsonl, fingerprint, validate
from .evaluation import contribution_scores, evaluate, fit, paired_bootstrap
from .fixture import generate
from .model import ModelConfig, ThetaNN


def run(out: Path, epochs=100):
    if epochs < 1:
        raise ValueError("epochs must be positive")
    torch.set_num_threads(1)
    torch.use_deterministic_algorithms(True)
    rows = generate()
    validate(rows)
    transform = Transform.fit(rows)
    subsets = {split: [r for r in rows if r["split"] == split] for split in SPLITS}
    batches = {split: transform.batch(group) for split, group in subsets.items()}
    counts = torch.bincount(batches["train"]["points_class"], minlength=5)
    config = ModelConfig(d_embed=8, hidden=(32, 16), dropout=0.0, n_seasons=len(transform.seasons) + 1,
                         lambdas={h: 0.1 for h in ("turnover", "zone", "make", "oreb", "ft")})
    results, training, models = {}, {}, {}
    for name in ("context_only", "one_hot", "theta_nn"):
        torch.manual_seed(43)
        if name == "theta_nn":
            model = ThetaNN(len(transform.vocabulary) + 1, config, counts)
        elif name == "one_hot":
            model = OneHotPoints(len(transform.vocabulary) + 1, 4, counts)
            with torch.no_grad():
                model.table.weight.zero_()
        else:
            model = ContextNull(4, counts)
        training[name] = fit(model, batches["train"], batches["validation"], epochs=epochs)
        results[name] = evaluate(model, batches["test"], subsets["test"], transform.v4plus)
        models[name] = model
    comparisons = {name: paired_bootstrap(results["theta_nn"]["game_nll"], results[name]["game_nll"])
                   for name in ("context_only", "one_hot")}
    scores = contribution_scores(models["theta_nn"], transform, batches["test"], subsets["test"])
    report = {"kind": "newly reproduced synthetic demonstration", "fixture_seed": 17, "training_seed": 43,
              "fixture_sha256": fingerprint(rows), "python": platform.python_version(), "torch": torch.__version__,
              "device": "cpu", "threads": 1, "max_epochs": epochs, "players": 24,
              "corpus": {"games": len({r["game_id"] for r in rows}), "possessions": len(rows)},
              "splits": {s: {"games": len({r["game_id"] for r in group}), "possessions": len(group)} for s, group in subsets.items()},
              "transform": {"context_columns": ["home_off", "margin_bucket", "period", "clock_band"],
                            "train_mean": transform.mean.tolist(), "train_std": transform.std.tolist(), "v4plus": transform.v4plus},
              "models": results, "training": training, "paired_comparisons": comparisons,
              "gates": {"synthetic_nll_vs_both_baselines": all(x["passes_lower_nll_gate"] for x in comparisons.values()),
                        "real_player_value_validity": "not evaluated", "epm_comparison": "not evaluated"}}
    out.mkdir(parents=True, exist_ok=True)
    (out / "fixture.jsonl").write_text(canonical_jsonl(rows), encoding="utf-8", newline="\n")
    (out / "evaluation.json").write_text(json.dumps(report, indent=2, allow_nan=False) + "\n", encoding="utf-8", newline="\n")
    with (out / "player_scores.csv").open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(scores[0]))
        writer.writeheader()
        writer.writerows(scores)
    lines = ["# Synthetic evaluation report", "", "Generated by the working public example. All players and possessions are invented.", "",
             "64 games / 3,072 possessions / 24 synthetic players. Training: 40 games; validation: 12 games; test: 12 games.", "",
             "| Model | Test NLL (lower is better) | Expected-points MSE | Selected epoch |", "|---|---:|---:|---:|"]
    for name, result in results.items():
        lines.append(f"| {name} | {result['game_mean_nll']:.6f} | {result['expected_points_mse']:.6f} | {training[name]['selected_epoch']} |")
    lines += ["", "Paired 90% intervals resample the 12 test games 2,000 times. Differences are ThetaNN minus baseline.", "",
              "| Baseline | NLL difference | 90% interval | Entire interval below zero? |", "|---|---:|---|---|"]
    for name, result in comparisons.items():
        lines.append(f"| {name} | {result['mean_delta_nll']:.6f} | [{result['ci90_low']:.6f}, {result['ci90_high']:.6f}] | {result['passes_lower_nll_gate']} |")
    lines += ["", "This smoke benchmark does not evaluate NBA player ranking accuracy, causal impact, EPM, temporal generalization, or all historical gates.",
              "The simplified generator uses independent random lineups and at most one field-goal attempt. Its planted signal is easier than real basketball.",
              "One seed and 12 test games support a working demonstration, not a robust model-selection claim.", "",
              "The contribution CSV contains centered points-per-100 replacement estimates for invented players; these are not real athlete ratings.", "",
              f"Fixture SHA-256: `{report['fixture_sha256']}`.", f"Python {report['python']}; PyTorch {report['torch']}; CPU; one thread.", ""]
    (out / "evaluation.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=Path("output/demo"))
    parser.add_argument("--epochs", type=int, default=100)
    args = parser.parse_args()
    report = run(args.out, args.epochs)
    print(f"Synthetic corpus: {report['corpus']['possessions']:,} possessions across {report['corpus']['games']} games")
    for name, result in report["models"].items():
        print(f"{name:14s} test NLL: {result['game_mean_nll']:.6f}")
    print(f"Wrote {args.out / 'evaluation.md'}, evaluation.json, fixture.jsonl, player_scores.csv")


if __name__ == "__main__":
    main()
